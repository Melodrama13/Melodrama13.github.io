import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { createHash } from 'node:crypto';
import { STATIC_CORNER_PRESETS, STATIC_CORNER_VARIANTS, STATIC_SURFACE_TOKENS, STATIC_SURFACE_MODES } from './staticCornerPresets.js';
import { createContinuousCornerGeometry, insetContinuousCornerGeometry, offsetContinuousCornerGeometry } from './corners/continuousCornerGeometry.js';
import { createStaticCornerShadowImages } from './corners/staticCornerShadow.js';
import { createStaticCornerCssClipDeclarations } from './corners/staticCornerCssClip.js';
import { createStaticCornerLensSvg } from './corners/staticCornerLens.js';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const widths = [1, 2, 3, 5, 6];
const sides = ['top', 'right', 'bottom', 'left'];
const triangles = { top: 'M0 0H128L64 64Z', right: 'M128 0V128L64 64Z', bottom: 'M0 128H128L64 64Z', left: 'M0 0V128L64 64Z' };

function write(file, value) {
  if (!fs.existsSync(file) || fs.readFileSync(file, 'utf8') !== value) {
    fs.mkdirSync(path.dirname(file), { recursive: true });
    fs.writeFileSync(file, value);
  }
}

export function generateStaticCorners() {
  const css = ['/* Generated by scripts/generateStaticCorners.mjs. Do not hand-edit. */'];
  css.push(`:root{${Object.entries(STATIC_SURFACE_TOKENS).map(([name,value])=>`${name}:${value}`).join(';')}}`);
  const blocks = new Map();
  const paintClips = new Map();
  for (const [name, profiles] of Object.entries(STATIC_CORNER_PRESETS)) {
    const box = 128;
    const geometry = createContinuousCornerGeometry({ width: box, height: box, profiles });
    const r = geometry.radii;
    const cuts = [Math.max(r[0], r[1]), Math.max(r[1], r[2]), Math.max(r[2], r[3]), Math.max(r[3], r[0])].map(value => Math.max(1, value));
    const defs = [`<path id="outer" d="${geometry.path}"/>`];
    for (const side of sides) defs.push(`<clipPath id="${side}"><path d="${triangles[side]}"/></clipPath>`);
    const cells = [];
    const add = (id, paint) => {
      const i = cells.length, x = i % 6 * box, y = Math.floor(i / 6) * box;
      cells.push(`<view id="${id}" viewBox="${x} ${y} 128 128"/><g transform="translate(${x} ${y})">${paint}</g>`);
    };
    add('fill', '<use href="#outer" fill="white"/>');
    const content = insetContinuousCornerGeometry(geometry, 1);
    add('innerFill1', `<path d="${content.path}" transform="translate(1 1)" fill="white"/>`);
    for (const width of widths) {
      const inner = insetContinuousCornerGeometry(geometry, width);
      defs.push(`<mask id="ring${width}" maskUnits="userSpaceOnUse" x="0" y="0" width="128" height="128"><use href="#outer" fill="white"/><path d="${inner.path}" transform="translate(${width} ${width})" fill="black"/></mask>`);
      const paint = `<rect width="128" height="128" fill="white" mask="url(#ring${width})"/>`;
      add(`stroke${width}`, paint);
      for (const side of sides) add(`${side}${width}`, `<g clip-path="url(#${side})">${paint}</g>`);
    }
    add('dashed1', `<path d="${insetContinuousCornerGeometry(geometry, .5).path}" transform="translate(.5 .5)" fill="none" stroke="white" stroke-width="1" stroke-dasharray="4 3"/>`);
    const activeBase = createContinuousCornerGeometry({ width: 122, height: 122, profiles });
    defs.push(`<mask id="active-ring" maskUnits="userSpaceOnUse" x="0" y="0" width="128" height="128"><path d="${offsetContinuousCornerGeometry(activeBase, 3).path}" fill="white"/><path d="${activeBase.path}" transform="translate(3 3)" fill="black"/></mask>`);
    add('active', '<rect width="128" height="128" fill="white" mask="url(#active-ring)"/>');
    const svg = `<svg xmlns="http://www.w3.org/2000/svg" width="128" height="128" viewBox="0 0 128 128"><defs>${defs.join('')}</defs>${cells.join('')}</svg>`;
    write(path.join(root, 'public/ui/corners', `${name}.svg`), svg);
    const version = createHash('sha256').update(svg).digest('hex').slice(0, 8);
    const url = id => `url('/ui/corners/${name}.svg?v=${version}#${id}')`;
    const shadowUrls = {};
    for (const [appearance, shadow] of Object.entries(createStaticCornerShadowImages(geometry))) {
      const file = `${name}-shadow-${appearance}.svg`;
      write(path.join(root, 'public/ui/corners', file), shadow);
      shadowUrls[appearance] = `url('/ui/corners/${file}?v=${createHash('sha256').update(shadow).digest('hex').slice(0,8)}')`;
    }
    const declarations = [
      `--ui-static-fill-mask:${url('fill')}`, `--ui-static-mask-slice:${cuts.join(' ')}`, `--ui-static-mask-width:${cuts.map(v => v + 'px').join(' ')}`,
      `--ui-static-inner-fill-mask:${url('innerFill1')}`,
      `--ui-static-lower-mask-width:0px ${cuts.slice(1).map(v => v + 'px').join(' ')}`,
      `--ui-static-radius:${r.map(v => v + 'px').join(' ')}`, `--ui-corner-radii:${r.map(v => v + 'px').join(' ')}`,
      `--ui-corner-resolved-curve:${profiles[0].curve}`, `--ui-corner-profiles:${JSON.stringify(profiles)}`,
      `--ui-static-active-mask:${url('active')}`, `--ui-static-active-slice:${cuts.map(v => v + 3).join(' ')}`, `--ui-static-active-width:${cuts.map(v => v + 3 + 'px').join(' ')}`
    ];
    // Only these existing presets occur in the activity/precedent overlay.
    // Keep its native fill/ring clips offline, with no element measurements.
    if (['panel','panel-compact','panel-phone','group','compact'].includes(name)) {
      paintClips.set(name,createStaticCornerCssClipDeclarations(geometry,{shadowPadding:name.startsWith('panel')?24:0}));
    }
    declarations.push(`--ui-static-shadow-light:${shadowUrls.light}`,`--ui-static-shadow-dark:${shadowUrls.dark}`,`--ui-static-shadow-slice:${cuts.map(v=>v+24).join(' ')}`,`--ui-static-shadow-width:${cuts.map(v=>`calc(var(--ui-static-shadow-enabled,0) * ${v+24}px)`).join(' ')}`);
    for (const width of widths) {
      declarations.push(`--ui-static-mask-stroke-${width}:${url('stroke' + width)}`);
      for (const side of sides) declarations.push(`--ui-static-mask-${side}-${width}:${url(side + width)}`);
    }
    declarations.push(`--ui-static-mask-stroke-dashed-1:${url('dashed1')}`);
    const block = declarations.join(';');
    blocks.set(name, block);
    css.push(`[data-ui-static-corner="${name}"]{${block}}`);
  }
  for (const variant of STATIC_CORNER_VARIANTS) {
    const rule = `${variant.selector}[data-ui-static-corner]{${blocks.get(variant.preset)}}`;
    css.push(variant.media ? `@media ${variant.media}{${rule}}` : rule);
  }
  for (const mode of STATIC_SURFACE_MODES) {
    const rules=[`:root{${Object.entries(mode.tokens).map(([name,value])=>`${name}:${value}`).join(';')}}`];
    for(const [preset,variant]of Object.entries(mode.presets))rules.push(`[data-ui-static-corner="${preset}"]{${blocks.get(variant)}}`);
    // Repeat structural selectors at the same specificity, after base rules.
    // A simple attribute override would lose to :has() and panel ID variants.
    for(const variant of STATIC_CORNER_VARIANTS){
      const preset=mode.presets[variant.preset]||variant.preset;
      const rule=`${variant.selector}[data-ui-static-corner]{${blocks.get(preset)}}`;
      rules.push(variant.media?`@media ${variant.media}{${rule}}`:rule);
    }
    css.push(`@media ${mode.media}{${rules.join('\n')}}`);
  }
  // Emit overlay-only clips once, outside the reusable global preset blocks.
  // Sharing outer/inner coordinate lists also avoids copying each ring twice.
  const clipRule=(name,selector)=>`${selector}{${Object.entries(paintClips.get(name)).map(([key,value])=>`${key}:${value}`).join(';')}}`;
  const panelSelector=":root[data-ui-glass-mode='frosted'] .precedent-panel[data-ui-static-corner='panel']";
  css.push(clipRule('panel',panelSelector));
  for(const name of['group','compact'])css.push(clipRule(name,`:root[data-ui-glass-mode='frosted'] .precedent-panel [data-ui-static-corner='${name}']`));
  for(const mode of STATIC_SURFACE_MODES)css.push(`@media ${mode.media}{${clipRule(`panel-${mode.name}`,panelSelector)}}`);
  write(path.join(root, 'src/styles/static-corner-presets.generated.css'), css.join('\n') + '\n');
  write(path.join(root,'public/ui/corners/editor-lens-bevel.svg'),createStaticCornerLensSvg(STATIC_CORNER_PRESETS.panel));
  return { presets: blocks.size, assets: blocks.size * 3 + 1 };
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) console.log(generateStaticCorners());
