// Build-time only: bake signed distance and normal textures for fixed corners.
import { mkdir, readFile, writeFile } from 'node:fs/promises';
import { createContinuousCornerGeometry, offsetContinuousCornerGeometry, sampleContinuousCorner } from './corners/continuousCornerGeometry.js';

const grid = 64, range = 3, distanceScale = 4096, normalScale = 32767;
const tables = {};
for (const curve of [1.5, 2]) {
  const base = createContinuousCornerGeometry({ width: 2, height: 2, radii: 1, curve });
  const expanded = offsetContinuousCornerGeometry(base, 2);
  const values = new Int16Array((grid + 1) ** 2 * 3);
  for (let y = 0; y <= grid; y++) for (let x = 0; x <= grid; x++) {
    const sample = sampleContinuousCorner(expanded, 3 - x / grid * range, 3 - y / grid * range);
    const index = (y * (grid + 1) + x) * 3;
    values[index] = Math.round((sample.distance - 2) * distanceScale);
    values[index + 1] = Math.round(-sample.normalX * normalScale);
    values[index + 2] = Math.round(-sample.normalY * normalScale);
  }
  const bytes = Buffer.alloc(values.length * 2);
  values.forEach((value, index) => bytes.writeInt16LE(value, index * 2));
  tables[curve] = bytes.toString('base64');
}
await mkdir(new URL('../src/ui/generated/', import.meta.url), { recursive: true });
const output = new URL('../src/ui/generated/staticCornerOpticsData.js', import.meta.url);
const source = `// Generated by scripts/generateCornerOptics.mjs. Do not edit.\nexport const STATIC_CORNER_OPTICS = ${JSON.stringify({ grid, range, distanceScale, normalScale, tables })};\n`;
if (await readFile(output, 'utf8').catch(() => '') !== source) await writeFile(output, source);
